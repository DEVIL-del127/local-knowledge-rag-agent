# -*- coding: utf-8 -*-
"""cleaner P1 专项测试：错别字纠正（实体词典容错）+ 口语规范化

原则：
- 错别字只纠正 长度≥3 的实体词（同音+编辑距离≤1），防误伤（"语文"≠"余文"）
- 口语规范化只做语义安全映射（"咋/啥"类），不做有歧义改写（"搞→做"不做）
"""
import sys
sys.stdout.reconfigure(encoding="utf-8")
from cleaner import clean

# ---------- 错别字纠正矩阵 ----------
TYPO_CASES = [
    # (查询, 期望清洗后)
    ("张昭招2024年的论文", "张昭昭2024年的论文"),       # 作者同音形近（3字）
    ("贝叶丝模型", "贝叶斯模型"),                       # 主题词同音形近（3字）
    ("神精网络", "神经网络"),                           # 主题词同音形近（4字）
    ("扩散摸型", "扩散模型"),                           # 主题词同音形近（4字）
    ("语文学习", "语文学习"),                           # 2字作者不纠正（防误伤）
    ("余文是谁", "余文是谁"),                           # 2字作者原样
    ("时间序列预测", "时间序列预测"),                   # 正确词不误改
    ("张昭昭2024年的论文", "张昭昭2024年的论文"),       # 正确作者原样
    ("回归状态网络", "回归状态网络"),               # 与"回声状态网络"不同音，不纠
]

# ---------- 口语规范化矩阵 ----------
COLLOQUIAL_CASES = [
    ("咋样能找到贝叶斯的论文", "如何能找到贝叶斯的论文"),
    ("库里有啥贝叶斯的论文", "库里有什么贝叶斯的论文"),
    ("咋才能找到", "怎么才能找到"),
    ("瞅瞅有哪些论文", "看看有哪些论文"),
    ("搞清楚这个模型", "搞清楚这个模型"),              # "搞"不替换（保护）
    ("发一下2024年的论文", "发一下2024年的论文"),       # "发一下"不替换（语义模糊）
]

# ---------- 全流程回归（清洗后下游不受损） ----------
FLOW_CASES = [
    ("我想看看张昭招2024年的论文", "张昭昭2024年的论文"),
    ("嗯那个，库里有啥扩散摸型的论文啊", "库里有什么扩散模型的论文"),
    ("帮我查一下咋样才能找到贝叶斯的论文", "如何才能找到贝叶斯的论文"),
]


def main():
    fails = []
    ok = 0
    total = len(TYPO_CASES) + len(COLLOQUIAL_CASES) + len(FLOW_CASES)

    for q, exp in TYPO_CASES + COLLOQUIAL_CASES + FLOW_CASES:
        got = clean(q).cleaned
        if got == exp:
            ok += 1
        else:
            fails.append((q, exp, got))

    print(f"cleaner P1 测试: 总计 {total}, 通过 {ok}, 失败 {len(fails)}, 准确率 {ok/total*100:.1f}%")
    if fails:
        print("\n=== 失败 ===")
        for q, e, g in fails:
            print(f"  Q: {q}\n     期望={e}\n     实际={g}")
        sys.exit(1)
    else:
        print("全部通过 ✅")


if __name__ == "__main__":
    main()
